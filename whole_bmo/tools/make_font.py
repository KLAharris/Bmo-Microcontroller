FIRST, LAST = 32, 95          # ' ' .. '_'  (lowercase is folded to uppercase)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "gfx_font_data.h"
    lines = ["/* gfx_font_data.h — GENERATED by tools/make_font.py. Do not edit. */",
             "/* 5x7 font, chars 32..95. One byte per row, bit 4 = leftmost pixel. */",
             "#define FONT_FIRST 32", "#define FONT_LAST  95", "",
             "static const uint8_t FONT5X7[FONT_LAST - FONT_FIRST + 1][7] = {"]
    prev = Image.new("L", ((LAST - FIRST + 1) * 6 * 3, 8 * 3), 255)
    for i, code in enumerate(range(FIRST, LAST + 1)):
        rows = G.get(chr(code), G['?'])
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(code)
        vals = [sum(1 << (4 - x) for x, ch in enumerate(r) if ch == '#') for r in rows]
        lines.append("    { " + ", ".join(f"0x{v:02X}" for v in vals) + " },  /* '" +
                     (chr(code) if chr(code) not in "\\*/" else ' ') + "' */")
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == '#':
                    for a in range(3):
                        for b in range(3):
                            prev.putpixel(((i * 6 + x) * 3 + a, y * 3 + b), 0)
    lines += ["};", ""]
    open(out, "w").write("\n".join(lines))
    prev.save("font_preview.png")
    print(f"wrote {out} and font_preview.png")


if __name__ == "__main__":
    main()
